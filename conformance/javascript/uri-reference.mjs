// The URI-reference rule of RFC 3986, appendix A, as the Python reference
// checks the schema's `uri-reference` format. src/itself/_formats.py builds
// the pattern from the RFC's named rules, using only syntax that Python and
// JavaScript read the same way; this file keeps the result, and
// tests/test_conformance.py fails if the two differ. The pattern is
